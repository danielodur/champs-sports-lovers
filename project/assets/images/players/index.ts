const normalizePlayerName = (playerName: string): string => {
  return playerName
    .toLowerCase()
    .replace(/[àáâãäå]/g, "a")
    .replace(/[èéêë]/g, "e")
    .replace(/[ìíîï]/g, "i")
    .replace(/[òóôõö]/g, "o")
    .replace(/[ùúûü]/g, "u")
    .replace(/[ñ]/g, "n")
    .replace(/[ç]/g, "c")
    .replace(/[^a-z0-9]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "");
};

export const getPlayerImage = (playerName: string): any => {
  const normalizedName = normalizePlayerName(playerName);

  if (allPlayerImages.hasOwnProperty(normalizedName)) {
    return allPlayerImages[normalizedName as keyof typeof allPlayerImages];
  }

  const variations = [
    normalizedName.replace("_", ""),
    normalizedName.replace(/^([a-z])_/, "$1_"),
    normalizedName.replace(/_([a-z])$/, "_$1"),
    normalizedName.split("_").join(""),
    normalizedName.split("_").reverse().join("_"),
  ];

  for (const variation of variations) {
    if (allPlayerImages.hasOwnProperty(variation)) {
      return allPlayerImages[variation as keyof typeof allPlayerImages];
    }
  }

  return null;
};

export const hasRealImage = (playerName: string): boolean => {
  return getPlayerImage(playerName) !== null;
};

export { allPlayerImages, row1Images, row2Images };

export default getPlayerImage;
